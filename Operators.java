public class Operators {
    public static void main(String[] args) 
    {
        int a=10;
        int b=5;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);
        System.out.println(a!=b);
     
        
        //assignment operators
        a+=b;
        a-=b;
        a*=b;
        a/=b;
        a%=b;
        System.out.println(a);
        System.out.println(b);

        //Increment and Decrement operators
        System.out.println(++a);
        System.out.println(--a);
        

    }
    
}
