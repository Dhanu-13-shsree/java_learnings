public class TypeCasting {
    public static void main(String[] args) {
        int a=10;
        double b=a;
        System.out.println(b);
        
        //Widening conversation
        double c=10.5;
        int d=(int )c;


        //Implicit type cating
        int x=3;


        //Explicit type casting
        int y =5;
        int z =10;
        System.out.println("x/z"+((float)x/z));

    }
    
}
